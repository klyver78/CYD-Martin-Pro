#!/usr/bin/env python3
"""Regenerate src/api_certs.h from Mozilla's CA bundle (pip install certifi).

The tracker talks to two hosts over HTTPS: the price API and GitHub Pages (OTA + portfolio.json).
mbedTLS accepts several concatenated roots, so we ship a handful of widely used ones; that keeps
the device working when a host rotates to another CA in the same set.

Usage: python3 tools/gen_certs.py > src/api_certs.h
"""
import re
import sys

import certifi

WANT = [
    "DigiCert Global Root CA",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "DigiCert High Assurance EV Root CA",
    "Baltimore CyberTrust Root",
    "ISRG Root X1",
    "Amazon Root CA 1",
    "GlobalSign Root CA",
    "GlobalSign Root CA - R3",
    "GlobalSign Root R46",
    "USERTrust RSA Certification Authority",
    "Go Daddy Root Certificate Authority - G2",
]

text = open(certifi.where(), encoding="utf-8").read()
found = {}
for label, body in re.findall(
    r'# Label: "([^"]+)".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----\n)',
    text,
    re.S,
):
    if label in WANT and label not in found:
        found[label] = body

names = [n for n in WANT if n in found]
missing = [n for n in WANT if n not in found]
if missing:
    print(f"warning: not in this certifi build: {', '.join(missing)}", file=sys.stderr)
if len(names) < 6:
    sys.exit("too few roots found - is certifi installed and up to date?")

print(f"""// Auto-generated by tools/gen_certs.py - do not edit by hand.
// Root CAs for HTTPS: the price API (Yahoo Finance) and GitHub Pages (OTA + portfolio.json).
// Source: Mozilla CA bundle via Python certifi. Several roots = robust to CA rotation.
// Roots: {', '.join(names)}.
#pragma once
static const char API_ROOT_CAS[] =
R"CERTS(
{''.join(found[n] for n in names)})CERTS";""")
